"""Generates hooks/vantablack-scene.ts: Vantablack's dot hands as a vector backdrop.

Reads Omarchy's themes/vantablack/backgrounds/0-dot-hands.jpg (kept in source/), finds
every white dot and redraws it exactly as a vector dot of its own size, so nothing is
lost to tracing. A soft band of light sweeps slowly across the hands, a nod to the
theme's animated intro. Each dot is a zero-length round-capped stroke: tiny in SVG.

Needs NumPy and OpenCV (opencv-python-headless).

    python scripts/make_vantablack_scene.py [image] [--out hooks/vantablack-scene.ts] [--html preview.html]
"""
import argparse
from pathlib import Path

import cv2
import numpy as np

HERE = Path(__file__).resolve().parent.parent
p = argparse.ArgumentParser()
p.add_argument('image', nargs='?', default=str(HERE / 'source' / 'vantablack-dot-hands.jpg'))
p.add_argument('--out', default=str(HERE / 'hooks' / 'vantablack-scene.ts'))
p.add_argument('--html')
args = p.parse_args()

im = cv2.imread(args.image, cv2.IMREAD_GRAYSCALE)
assert im is not None, f'cannot read {args.image}'
h, w = im.shape
K = 0.5  # viewBox units per image pixel
VW, VH = round(w * K), round(h * K)

_, bw = cv2.threshold(im, 60, 255, cv2.THRESH_BINARY)
n, _, stats, cents = cv2.connectedComponentsWithStats(bw)
areas = stats[1:, 4]
cents = cents[1:]
keep = areas >= 8
areas, cents = areas[keep], cents[keep]
split = (np.percentile(areas, 5) + np.percentile(areas, 95)) / 2


def dots_path(points):
    """Rows of zero-length strokes, each row with relative moves."""
    pts = sorted((round(y * K), round(x * K)) for x, y in points)
    out, row_y, last_x = [], None, 0
    for y, x in pts:
        if y != row_y:
            out.append(f'M{x} {y}h0')
            row_y, last_x = y, x
        else:
            out.append(f'm{x - last_x} 0h0')
            last_x = x
    return ''.join(out)


small = cents[areas < split]
large = cents[areas >= split]
r_small = float(np.sqrt(np.median(areas[areas < split]) / np.pi) * K)
r_large = float(np.sqrt(np.median(areas[areas >= split]) / np.pi) * K)
d_small, d_large = dots_path(small), dots_path(large)

dots = (f'<path d="{d_small}" stroke-width="{2 * r_small:.1f}"/>'
        f'<path d="{d_large}" stroke-width="{2 * r_large:.1f}"/>')

svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VW} {VH}" preserveAspectRatio="xMidYMid slice">'
    '<style>'
    '.sweep { animation: sweep 14s ease-in-out infinite; }'
    '.base { animation: breathe 10s ease-in-out infinite; }'
    f'@keyframes sweep {{ 0% {{ transform: translateX(-{VW // 2}px); }} 70%, 100% {{ transform: translateX({VW}px); }} }}'
    '@keyframes breathe { 0%, 100% { opacity: 0.78; } 50% { opacity: 0.9; } }'
    '</style>'
    '<defs>'
    '<linearGradient id="band" x1="0" y1="0" x2="1" y2="0">'
    '<stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset="0.5" stop-color="#fff" stop-opacity="1"/>'
    '<stop offset="1" stop-color="#fff" stop-opacity="0"/></linearGradient>'
    f'<mask id="lit" maskUnits="userSpaceOnUse" x="0" y="0" width="{VW}" height="{VH}">'
    f'<rect class="sweep" x="0" y="0" width="{VW // 3}" height="{VH}" fill="url(#band)"/></mask>'
    '</defs>'
    f'<rect width="{VW}" height="{VH}" fill="#000"/>'
    f'<g class="base" fill="none" stroke="#e6e6e6" stroke-linecap="round">{dots}</g>'
    f'<g mask="url(#lit)" fill="none" stroke="#ffffff" stroke-linecap="round" opacity="0.9">{dots}</g>'
    '</svg>'
)

for bad in ('<image', 'href', 'data:', '\\', '<![', "'"):
    assert bad not in svg, bad
assert len(svg) < 131072, len(svg)
print(f'{len(small)} small + {len(large)} large dots, {len(svg)} chars')

Path(args.out).write_text(
    '// Generated by scripts/make_vantablack_scene.py from Omarchy\'s vantablack dot-hands wallpaper.\n'
    "// Don't edit by hand; change the script and rerun it.\n"
    f'export const VANTABLACK_SCENE_SVG = {svg!r}\n', encoding='utf-8', newline='\n')
if args.html:
    Path(args.html).write_text('<!doctype html><html><body style="margin:0;background:#000"><div style="width:100vw;height:100vh">'
                               + svg.replace('<svg ', '<svg width="100%" height="100%" ', 1) + '</div></body></html>', encoding='utf-8')
