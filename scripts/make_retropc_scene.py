"""Generates hooks/retropc-scene.ts: RetroPC's amber CRT tube as a vector backdrop.

Rebuilt from rondilley/omarchy-retropc-theme backgrounds/amber_tube.jpg, with colours
sampled from it: a black bezel, a rounded glass tube glowing faint amber toward the
middle, and a burned-in window. The wallpaper is smooth gradients, which tracing bands,
so it is drawn as shapes instead. Slow CRT motion on top: scanlines, a rolling refresh
band, a soft phosphor breathe and a blinking block cursor in the burned-in window.

Run from anywhere:  python scripts/make_retropc_scene.py  (or pass another output path).
"""
import sys
from pathlib import Path

OUTPUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / 'hooks' / 'retropc-scene.ts'

W, H = 1600, 1000
# The tube's glass, inset in the bezel; the sides bow out slightly like a real CRT.
L, T, R, B = 70, 32, 1530, 968
BOW = 10
RAD = 80


def tube(l, t, r, b, rad, bow):
    return (f'M{l + rad} {t} Q{(l + r) / 2:.0f} {t - bow} {r - rad} {t} Q{r} {t} {r} {t + rad} '
            f'Q{r + bow} {(t + b) / 2:.0f} {r} {b - rad} Q{r} {b} {r - rad} {b} '
            f'Q{(l + r) / 2:.0f} {b + bow} {l + rad} {b} Q{l} {b} {l} {b - rad} '
            f'Q{l - bow} {(t + b) / 2:.0f} {l} {t + rad} Q{l} {t} {l + rad} {t}Z')


svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice">
<style>
.glow {{ animation: breathe 7s ease-in-out infinite; }}
.roll {{ animation: roll 9s linear infinite; }}
.cursor {{ animation: blink 2.4s ease-in-out infinite; }}
@keyframes breathe {{ 0%, 100% {{ opacity: 0.9; }} 50% {{ opacity: 1; }} }}
@keyframes roll {{ from {{ transform: translateY(-260px); }} to {{ transform: translateY({H + 60}px); }} }}
@keyframes blink {{ 0%, 45% {{ opacity: 0.35; }} 55%, 95% {{ opacity: 0.04; }} 100% {{ opacity: 0.35; }} }}
</style>
<defs>
<radialGradient id="phosphor" cx="0.5" cy="0.47" r="0.62">
<stop offset="0" stop-color="#2e1500"/><stop offset="0.45" stop-color="#231000"/>
<stop offset="0.8" stop-color="#170b00"/><stop offset="1" stop-color="#0e0700"/></radialGradient>
<linearGradient id="bezel" x1="0" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="#0b0700"/><stop offset="1" stop-color="#110900"/></linearGradient>
<linearGradient id="band" x1="0" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="#ffb000" stop-opacity="0"/><stop offset="0.5" stop-color="#ffb000" stop-opacity="0.05"/>
<stop offset="1" stop-color="#ffb000" stop-opacity="0"/></linearGradient>
<linearGradient id="sheen" x1="0" y1="0" x2="0.6" y2="1">
<stop offset="0" stop-color="#ffcc66" stop-opacity="0.05"/><stop offset="0.35" stop-color="#ffcc66" stop-opacity="0"/></linearGradient>
<pattern id="scan" width="4" height="4" patternUnits="userSpaceOnUse">
<rect width="4" height="2" fill="#000" opacity="0.28"/></pattern>
<clipPath id="glass"><path d="{tube(L, T, R, B, RAD, BOW)}"/></clipPath>
<filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="6"/></filter>
<filter id="rimblur"><feGaussianBlur stdDeviation="3"/></filter>
</defs>
<rect width="{W}" height="{H}" fill="url(#bezel)"/>
<path d="{tube(L - 18, T - 16, R + 18, B + 16, RAD + 14, BOW)}" fill="#070400"/>
<path d="{tube(L - 6, T - 5, R + 6, B + 5, RAD + 4, BOW)}" fill="none" stroke="#1a0d00" stroke-width="3" filter="url(#rimblur)"/>
<g clip-path="url(#glass)">
<rect class="glow" x="0" y="0" width="{W}" height="{H}" fill="url(#phosphor)"/>
<g filter="url(#soft)" opacity="0.55">
<rect x="430" y="262" width="740" height="490" rx="10" fill="none" stroke="#3a1a00" stroke-width="8"/>
<rect x="520" y="470" width="190" height="34" fill="#331700"/>
<rect x="790" y="470" width="60" height="34" fill="#331700"/>
</g>
<rect class="cursor" x="872" y="472" width="22" height="30" fill="#ffb000" opacity="0.3" filter="url(#soft)"/>
<rect class="roll" x="0" y="0" width="{W}" height="220" fill="url(#band)"/>
<rect x="0" y="0" width="{W}" height="{H}" fill="url(#scan)"/>
<rect x="0" y="0" width="{W}" height="{H}" fill="url(#sheen)"/>
<path d="{tube(L, T, R, B, RAD, BOW)}" fill="none" stroke="#000" stroke-opacity="0.6" stroke-width="60" filter="url(#soft)"/>
</g>
</svg>'''

svg = ' '.join(svg.split())
assert len(svg) < 131072, len(svg)
for bad in ('<image', 'href', 'data:', '\\', '<![', "'"):
    assert bad not in svg, bad

OUTPUT.write_text(
    "// Generated by scripts/make_retropc_scene.py: RetroPC's amber CRT tube.\n"
    "// Don't edit by hand; change the script and rerun it.\n"
    f"export const RETROPC_SCENE_SVG = {svg!r}\n", encoding='utf-8', newline='\n')
print(f'{len(svg)} chars -> {OUTPUT}')
if len(sys.argv) > 2:
    Path(sys.argv[2]).write_text('<!doctype html><html><body style="margin:0;background:#000"><div style="width:100vw;height:100vh">'
                                 + svg.replace('<svg ', '<svg width="100%" height="100%" ', 1) + '</div></body></html>', encoding='utf-8')
